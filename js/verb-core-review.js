const coreGenericMeanings = new Set([
  'Het werkwoord beschrijft vooral een handeling of activiteit.',
  'Het werkwoord beschrijft een toestand, ervaring, houding of waarneming.',
  'Het onderwerp verandert van toestand, omvang, kwaliteit of situatie.',
]);

function validateReview(item) {
  const required = ['infinitive', 'meaning', 'semanticLabel', 'usage', 'synonymNote', 'past', 'pastPlural', 'participle', 'conjugationClass'];
  for (const field of required) {
    if (typeof item[field] !== 'string' || item[field].trim().length < 2) throw new Error(`${item.infinitive}: ongeldig veld ${field}`);
  }
  if (item.meaning.length < 35 || coreGenericMeanings.has(item.meaning)) throw new Error(`${item.infinitive}: definitie is generiek of te kort`);
  if (!Array.isArray(item.synonyms) || item.synonyms.length < 2 || new Set(item.synonyms).size !== item.synonyms.length) throw new Error(`${item.infinitive}: synoniemen zijn onvolledig of dubbel`);
  if (!Array.isArray(item.examples) || item.examples.length < 2) throw new Error(`${item.infinitive}: voorbeelden ontbreken`);
  if (item.presentForms.length !== 6 || item.pastForms.length !== 6 || item.perfectForms.length < 2) throw new Error(`${item.infinitive}: vervoeging is onvolledig`);
}

export function applyCoreVerbReviews(atlas) {
  const existingReviewed = new Set(atlas.filter((item) => item.reviewed === true).map((item) => item.infinitive));
  for (const item of coreVerbReviews) {
    validateReview(item);
    if (existingReviewed.has(item.infinitive)) continue;
    let verb = atlas.find((candidate) => candidate.infinitive === item.infinitive);
    if (!verb) { verb = { infinitive: item.infinitive }; atlas.push(verb); }
    Object.assign(verb, item, {
      synonyms: [...item.synonyms], examples: [...item.examples], relatedWords: [...item.relatedWords],
      presentForms: [...item.presentForms], pastForms: [...item.pastForms], perfectForms: [...item.perfectForms],
      sentencePatterns: { ...item.sentencePatterns },
    });
  }
  atlas.sort((a, b) => a.infinitive.localeCompare(b.infinitive, 'nl-NL'));
  return atlas;
}
