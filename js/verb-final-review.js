function validateFinalReview(item) {
  if (!item.meaning || item.meaning.length < 35) throw new Error(`${item.infinitive}: definitie te kort`);
  if (!item.usage || item.usage.length < 35) throw new Error(`${item.infinitive}: gebruiksnotitie te kort`);
  if (!item.synonymNote || item.synonymNote.length < 45) throw new Error(`${item.infinitive}: synoniemnotitie te kort`);
  if (!Array.isArray(item.synonyms) || item.synonyms.length < 1) throw new Error(`${item.infinitive}: synoniemen ontbreken`);
  if (!Array.isArray(item.examples) || item.examples.length < 2) throw new Error(`${item.infinitive}: voorbeelden ontbreken`);
  if (item.presentForms.length !== 6 || item.pastForms.length !== 6 || item.perfectForms.length < 2) throw new Error(`${item.infinitive}: vervoeging onvolledig`);
}

export function applyFinalVerbReviews(atlas) {
  for (const item of finalVerbReviews) {
    validateFinalReview(item);
    let verb = atlas.find((candidate) => candidate.infinitive === item.infinitive);
    if (!verb) { verb = { infinitive: item.infinitive }; atlas.push(verb); }
    Object.assign(verb, item, {
      synonyms: [...item.synonyms], examples: [...item.examples], relatedWords: [...item.relatedWords],
      presentForms: [...item.presentForms], pastForms: [...item.pastForms], perfectForms: [...item.perfectForms],
      sentencePatterns: { ...item.sentencePatterns },
    });
  }
  atlas.sort((a, b) => a.infinitive.localeCompare(b.infinitive, 'nl-NL'));
  return atlas;
}
